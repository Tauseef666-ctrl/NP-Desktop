package net.newpipe.app.provider

/**
 * One selectable subtitle/caption track of a stream page, independent of any provider. Providers fill
 * in only what they know; the UI lists the tracks it really received and never invents any.
 *
 * @param id Stable identifier of the track within a stream page, unique across its tracks.
 * @param languageTag BCP-47-ish language tag (for example `en`, `de`, `en-US`), or the provider's
 *   raw code when it exposes no proper tag.
 * @param displayName Human-readable language name shown to the user.
 * @param isAutoGenerated True when the provider generated the captions automatically (for example
 *   YouTube auto-captions) rather than an author-supplied track.
 * @param format Subtitle container/format hint (for example `vtt`, `ttml`), or null when unknown.
 * @param url Direct URL of the subtitle document, or null when the provider does not expose one.
 */
data class SubtitleTrack(
    val id: String,
    val languageTag: String,
    val displayName: String,
    val isAutoGenerated: Boolean = false,
    val format: String? = null,
    val url: String? = null
)
