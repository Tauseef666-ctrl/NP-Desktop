package net.newpipe.app.provider

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNull
import kotlin.test.assertTrue

class ExtractorSubtitleTest {

    @Test
    fun `happy path maps fields and ids through unchanged`() {
        val result = ExtractorMediaProvider.pureSubtitleTracks(
            listOf(
                ExtractorMediaProvider.Companion.SubtitleFields(
                    languageTag = "en",
                    displayName = "English",
                    isAutoGenerated = false,
                    format = "vtt",
                    url = "https://example.com/en.vtt"
                ),
                ExtractorMediaProvider.Companion.SubtitleFields(
                    languageTag = "de",
                    displayName = "German",
                    isAutoGenerated = true,
                    format = "ttml",
                    url = "https://example.com/de.ttml"
                )
            )
        )
        assertEquals(
            listOf(
                SubtitleTrack(
                    id = "en|manual|vtt",
                    languageTag = "en",
                    displayName = "English",
                    isAutoGenerated = false,
                    format = "vtt",
                    url = "https://example.com/en.vtt"
                ),
                SubtitleTrack(
                    id = "de|auto|ttml",
                    languageTag = "de",
                    displayName = "German",
                    isAutoGenerated = true,
                    format = "ttml",
                    url = "https://example.com/de.ttml"
                )
            ),
            result
        )
    }

    @Test
    fun `blank display name falls back to language tag`() {
        val result = ExtractorMediaProvider.pureSubtitleTracks(
            listOf(
                ExtractorMediaProvider.Companion.SubtitleFields(
                    languageTag = "fr",
                    displayName = "  ",
                    isAutoGenerated = false,
                    format = "vtt",
                    url = "https://example.com/fr.vtt"
                )
            )
        )
        assertEquals(1, result.size)
        assertEquals("fr", result.single().displayName)
        assertEquals("fr", result.single().languageTag)
    }

    @Test
    fun `blank display name and language tag drops the entry`() {
        val result = ExtractorMediaProvider.pureSubtitleTracks(
            listOf(
                ExtractorMediaProvider.Companion.SubtitleFields(
                    languageTag = "   ",
                    displayName = "",
                    isAutoGenerated = false,
                    format = "vtt",
                    url = "https://example.com/x.vtt"
                )
            )
        )
        assertTrue(result.isEmpty())
    }

    @Test
    fun `blank format and url become null`() {
        val result = ExtractorMediaProvider.pureSubtitleTracks(
            listOf(
                ExtractorMediaProvider.Companion.SubtitleFields(
                    languageTag = "en",
                    displayName = "English",
                    isAutoGenerated = false,
                    format = "   ",
                    url = ""
                )
            )
        )
        assertEquals(1, result.size)
        assertNull(result.single().format)
        assertNull(result.single().url)
    }

    @Test
    fun `blank language tag falls back to display name`() {
        val result = ExtractorMediaProvider.pureSubtitleTracks(
            listOf(
                ExtractorMediaProvider.Companion.SubtitleFields(
                    languageTag = "  ",
                    displayName = "Español",
                    isAutoGenerated = false,
                    format = "vtt",
                    url = "https://example.com/es.vtt"
                )
            )
        )
        assertEquals(1, result.size)
        assertEquals("Español", result.single().languageTag)
        assertEquals("Español", result.single().displayName)
    }

    @Test
    fun `empty input returns empty output`() {
        assertTrue(ExtractorMediaProvider.pureSubtitleTracks(emptyList()).isEmpty())
    }

    @Test
    fun `auto and manual tracks with same language and format get different ids`() {
        val result = ExtractorMediaProvider.pureSubtitleTracks(
            listOf(
                ExtractorMediaProvider.Companion.SubtitleFields(
                    languageTag = "en",
                    displayName = "English",
                    isAutoGenerated = false,
                    format = "vtt",
                    url = "https://example.com/en.vtt"
                ),
                ExtractorMediaProvider.Companion.SubtitleFields(
                    languageTag = "en",
                    displayName = "English",
                    isAutoGenerated = true,
                    format = "vtt",
                    url = "https://example.com/en-auto.vtt"
                )
            )
        )
        assertEquals(2, result.size)
        assertEquals("en|manual|vtt", result[0].id)
        assertEquals("en|auto|vtt", result[1].id)
        assertTrue(result[0].id != result[1].id)
    }
}
